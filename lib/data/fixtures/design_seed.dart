/// Expanded demo dataset ready to seed a repository/DB.
class SeedData {
  SeedData({
    required this.workspaces,
    required this.accounts,
    required this.projects,
    required this.tickets,
    required this.translations,
    required this.viByTicketId,
  });

  final List<Workspace> workspaces;
  final List<Account> accounts;
  final List<Project> projects;
  final List<Ticket> tickets;
  final List<TranslationRecord> translations;

  /// Vietnamese source text for every ticket (used by the mock translation
  /// service so the Translate button produces real VI text in the demo).
  final Map<String, ({String title, String body})> viByTicketId;

  /// Build the full dataset from the seed rows, computing ids, hashes, relative
  /// timestamps (relative to [now]) and translation records for done/outdated.
  factory SeedData.build({DateTime? now}) {
    final base = now ?? DateTime.now();
    final projectsById = <String, Project>{};
    final tickets = <Ticket>[];
    final translations = <TranslationRecord>[];
    final viByTicketId = <String, ({String title, String body})>{};

    for (final s in kSeedTickets) {
      final projectId = '${s.acc}:${s.proj}';
      projectsById.putIfAbsent(
        projectId,
        () => Project(id: projectId, accountId: s.acc, name: s.proj),
      );
      final ticketId = '${s.acc}:${s.key}';
      viByTicketId[ticketId] = (title: s.titleVi, body: s.descVi);
      final hash = contentHash(s.title, s.desc);
      final account = kSeedAccounts.firstWhere((a) => a.id == s.acc);
      tickets.add(
        Ticket(
          id: ticketId,
          accountId: s.acc,
          projectId: projectId,
          providerType: account.providerType,
          externalKey: s.key,
          externalType: s.type,
          title: s.title,
          body: s.desc,
          priority: Priority.fromLevel(s.lv),
          status: UnifiedStatus.byId(s.status),
          providerStatus: s.status,
          sourceHash: hash,
          labels: s.labels,
          assignee: 'You',
          updatedAt: _ago(s.up, base),
        ),
      );

      if (s.tr == 'done' || s.tr == 'outdated') {
        translations.add(
          TranslationRecord(
            ticketId: ticketId,
            // 'done' matches current hash; 'outdated' intentionally differs.
            sourceHash: s.tr == 'done' ? hash : '$hash-prev',
            targetLang: 'vi',
            translatedTitle: s.titleVi,
            translatedBody: s.descVi,
            model: 'anthropic/claude-haiku-4-5',
            templateVersion: 'v1',
            createdAt: base.subtract(Duration(hours: s.tr == 'done' ? 0 : 26)),
          ),
        );
      }
    }

    return SeedData(
      workspaces: List.of(kSeedWorkspaces),
      accounts: List.of(kSeedAccounts),
      projects: projectsById.values.toList(),
      tickets: tickets,
      translations: translations,
      viByTicketId: viByTicketId,
    );
  }
}

/// Parse a relative "ago" token like `12m`, `3h`, `2d` into a timestamp.
DateTime _ago(String token, DateTime base) {
  final unit = token.substring(token.length - 1);
  final n = int.tryParse(token.substring(0, token.length - 1)) ?? 0;
  return switch (unit) {
    'm' => base.subtract(Duration(minutes: n)),
    'h' => base.subtract(Duration(hours: n)),
    'd' => base.subtract(Duration(days: n)),
    'w' => base.subtract(Duration(days: n * 7)),
    _ => base,
  };
}
